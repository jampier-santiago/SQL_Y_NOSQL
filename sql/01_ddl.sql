-- =====================================================================
-- 01_ddl.sql · Estructura de SeguroYa
-- Todos los objetos llevan el esquema explícito (seguroya.) para no
-- depender de SET search_path, que se pierde en consolas web que no
-- mantienen la sesión entre ejecuciones.
-- Los ids usan IDENTITY (secuencia real, 1, 2, 3...) en lugar de SERIAL,
-- porque SERIAL se comporta distinto en PostgreSQL y CockroachDB.
-- =====================================================================

CREATE SCHEMA seguroya;

CREATE TABLE seguroya.ciudades (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  departamento VARCHAR(60) NOT NULL
);

CREATE TABLE seguroya.productos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  linea VARCHAR(20) NOT NULL CHECK (linea IN ('movilidad','mascotas','salud','hogar')),
  prima_base NUMERIC(12,2) NOT NULL CHECK (prima_base > 0)
);

CREATE TABLE seguroya.clientes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento VARCHAR(15) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  fecha_nacimiento DATE NOT NULL,
  ciudad_id INT NOT NULL REFERENCES seguroya.ciudades (id),
  fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE seguroya.polizas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INT NOT NULL REFERENCES seguroya.clientes (id),
  producto_id INT NOT NULL REFERENCES seguroya.productos (id),
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  prima_mensual NUMERIC(12,2) NOT NULL CHECK (prima_mensual > 0),
  estado VARCHAR(12) NOT NULL DEFAULT 'activa'
    CHECK (estado IN ('activa','vencida','cancelada')),
  CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE seguroya.pagos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  poliza_id INT NOT NULL REFERENCES seguroya.polizas (id) ON DELETE CASCADE,
  fecha_pago DATE NOT NULL,
  valor NUMERIC(12,2) NOT NULL,
  metodo VARCHAR(15) NOT NULL CHECK (metodo IN ('tarjeta','pse','efectivo'))
);

CREATE TABLE seguroya.siniestros (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  poliza_id INT NOT NULL REFERENCES seguroya.polizas (id),
  fecha_ocurrencia DATE NOT NULL,
  tipo VARCHAR(30) NOT NULL,
  valor_reclamado NUMERIC(14,2) NOT NULL,
  valor_pagado NUMERIC(14,2),
  estado VARCHAR(12) NOT NULL
    CHECK (estado IN ('abierto','aprobado','rechazado','pagado'))
);
